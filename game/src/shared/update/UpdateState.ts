// BETA-FINAL PR12 / spec B6 - the shared update projection contract.
//
// One typed UpdateState flows main -> renderer over the allowlisted IPC
// surface; the renderer never receives a feed URL, a file path, a
// publisher blob or any updater primitive it could abuse - only this
// sanitized projection plus the four action channels (check / download /
// install-request / install-result). Both sides validate at the boundary:
// the renderer parses UpdateState before rendering, the main side parses
// the install result before installing.
//
// No Vue/Phaser/Node imports - this file must stay bundle-neutral.

import type { FlushResult } from '../session/FlushResult'

/** The phases of the one update state machine owned by the main-process
 *  UpdateService. 'unsupported' means this build carries no verified feed
 *  configuration (development builds, missing packaged manifest) - it is
 *  terminal for the lifetime of the process, not an error. */
export type UpdatePhase =
  | 'idle'
  | 'checking'
  | 'unavailable'
  | 'available'
  | 'downloading'
  | 'downloaded'
  | 'installing'
  | 'error'
  | 'unsupported'

export type UpdateErrorCode =
  | 'CHECK_FAILED'
  | 'DOWNLOAD_FAILED'
  | 'DOWNLOAD_CANCELLED'
  | 'CANDIDATE_CORRUPT'
  | 'MANIFEST_INVALID'
  | 'OLDER_VERSION'
  | 'WRONG_CHANNEL'
  | 'WRONG_ENVIRONMENT'
  | 'PUBLISHER_MISMATCH'
  | 'FEED_CONFIG_INVALID'
  | 'FLUSH_FAILED'
  | 'STALE_GENERATION'
  | 'INSTALL_TIMEOUT'
  | 'INSTALL_NOT_READY'
  | 'UNSUPPORTED'

export interface UpdateCandidate {
  /** Semver string from the verified feed manifest. */
  version: string
  /** Prerelease/channel tag proven to match this build's channel. */
  channel: string
  releaseName?: string
  releaseNotes?: string
  releaseDate?: string
}

export interface UpdateProgress {
  /** 0..100 - provider-reported, never computed renderer-side. */
  percent: number
  bytesPerSecond: number
  transferred: number
  total: number
}

export interface UpdateError {
  code: UpdateErrorCode
  message: string
  /** Retryable failures keep the downloaded/available candidate so an
   *  explicit user retry can resume; terminal ones cleared it. */
  retryable: boolean
}

export interface UpdateState {
  phase: UpdatePhase
  /** This running build (injected BuildIdentity values). */
  currentVersion: string
  currentBuildId: string
  /** Present whenever a verified candidate exists: 'available',
   *  'downloading', 'downloaded', 'installing' and retained across a
   *  retryable 'error'. Absent on 'unavailable'/'unsupported'/'idle'. */
  candidate?: UpdateCandidate
  /** Present only while 'downloading'. */
  progress?: UpdateProgress
  error?: UpdateError
}

