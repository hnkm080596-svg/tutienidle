/** The wire shape of an install result - the SAME FlushResult contract
 *  the quit path consumes (B1-D): request/generation binding plus the
 *  committed remote revision on success. */
export type UpdateInstallResult = FlushResult

/** Main -> renderer: the install preparation request quoting the
 *  main-minted requestId the result must carry. */
export interface UpdateInstallRequest {
  requestId: string
}

/** Main -> renderer: the pending install failed (bad result or timeout);
 *  the user picks retry (a NEW requestId) or later. Never implicit. */
