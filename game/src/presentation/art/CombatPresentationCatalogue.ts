/**
 * Fallback player entity key — same PNG as the mortal profile, different key.
 * Used when `combat-grid-view.ts` does not find the current profile's texture
 * loaded yet.
 *
 * Declared HERE rather than imported from `CombatPreload`: that module imports
 * this one, and the reverse edge would be a cycle.
 */
export const FALLBACK_PLAYER_ENTITY_KEY = 'player-mortal'

/**
 * Both declared forms of one entity, side by side. The catalogue emits ONE
 * of them - picked by ENTITY_ART_MODE - and keeps the other reachable through
 * `animatedArtFormFor`/`staticArtFormFor` so the dormant form's data stays
 * honest (the atlas/extent tests validate it against files on disk in
 * EITHER mode).
 */
function entityPresentation(
  staticArt: { texture: StaticEntityArt; idleMotion: IdleMotion },
  clips: CombatAnimationCatalogue,
): CombatEntityPresentation {
  return ENTITY_ART_MODE === 'animated'
    ? { kind: 'animated', clips }
    : { kind: 'static', texture: staticArt.texture, idleMotion: staticArt.idleMotion }
}

function buildCatalogue(): {
  entries: Map<string, CombatEntityPresentation>
  animatedForms: Map<string, CombatAnimationCatalogue>
  staticForms: Map<string, { texture: StaticEntityArt; idleMotion: IdleMotion }>
} {
  const animatedForms = new Map<string, CombatAnimationCatalogue>()
  const staticForms = new Map<string, { texture: StaticEntityArt; idleMotion: IdleMotion }>()

  const register = (
    entityKey: string,
    texture: StaticEntityArt,
    clips: CombatAnimationCatalogue,
  ): void => {
    animatedForms.set(entityKey, clips)
    staticForms.set(entityKey, { texture, idleMotion: idleMotionFor(entityKey) })
  }

  // Every player profile. Profiles sharing the mortal PNG (kiem_tu, the_tu)
  // collapse onto the mortal key - same art either way.
  for (const profile of Object.values(PLAYER_VISUAL_PROFILES)) {
    register(
      profile.combatTextureKey,
      {
        textureKey: profile.combatTextureKey,
        textureUrl: profile.combatTextureUrl.replace(/^\/+/, ''),
        sourceSize: { ...profile.combatSourceSize },
        extent:
          PLAYER_STATIC_EXTENTS[profile.combatTextureKey] ?? PLAYER_STATIC_EXTENT_MORTAL,
      },
      profile.combatTextureKey === PLAYER_VISUAL_PROFILES.mortal.combatTextureKey
        ? playerMortalCatalogue(profile.combatTextureKey)
        : placeholderClips(profile.combatTextureKey),
    )
  }

  register(
    FALLBACK_PLAYER_ENTITY_KEY,
    {
      textureKey: FALLBACK_PLAYER_ENTITY_KEY,
      textureUrl: PLAYER_VISUAL_PROFILES.mortal.combatTextureUrl.replace(/^\/+/, ''),
      sourceSize: { ...PLAYER_VISUAL_PROFILES.mortal.combatSourceSize },
      extent: PLAYER_STATIC_EXTENT_MORTAL,
    },
    playerMortalCatalogue(FALLBACK_PLAYER_ENTITY_KEY),
  )

  // Enemies are still images plus a bob in 'static' mode, placeholder clips
  // in 'animated' mode until their sheets are drawn.
  for (const templateId of MORTAL_ENEMY_TEMPLATE_IDS) {
    const textureKey = resolveEnemyTextureKey(templateId)

    if (!textureKey) {
      continue
    }

    register(
      textureKey,
      {
        textureKey,
        textureUrl: enemyTextureUrl(textureKey),
        sourceSize: { ...ENEMY_SOURCE_SIZE },
        // The Mortal PNGs are untrimmed: the animal fills its own file.
        extent: { x: 0, y: 0, w: 1, h: 1 },
      },
      placeholderClips(textureKey),
    )
  }

  // The wildcard entry - every spawnable entity without authored art resolves
  // to this at the resolution layer (entityAnimationKeyPrefix,
  // getOrCreateSprite), so "missing art" renders the SAME kind as everything
  // else instead of a Rectangle. Rectangle stays only for the double-fallback
  // where even the placeholder texture failed to load.
  register(
    PLACEHOLDER_ENTITY_KEY,
    {
      textureKey: PLACEHOLDER_STATIC_TEXTURE_KEY,
      textureUrl: PLACEHOLDER_STATIC_TEXTURE_URL,
      sourceSize: { ...PLACEHOLDER_STATIC_SOURCE_SIZE },
      extent: PLACEHOLDER_STATIC_EXTENT,
    },
    placeholderClips(PLACEHOLDER_ENTITY_KEY),
  )

  const entries = new Map<string, CombatEntityPresentation>()

  for (const entityKey of animatedForms.keys()) {
    const staticArt = staticForms.get(entityKey)
    const clips = animatedForms.get(entityKey)

    // register() sets both maps together - a missing half is a build bug,
    // not a reachable state.
    if (!staticArt || !clips) {
      continue
    }

    entries.set(entityKey, entityPresentation(staticArt, clips))
  }

  return { entries, animatedForms, staticForms }
}

const { entries: CATALOGUE, animatedForms: ANIMATED_FORMS, staticForms: STATIC_FORMS } =
  buildCatalogue()

/** Every entity key the catalogue knows. For the guards, and for preload. */
export function combatPresentationEntityKeys(): readonly string[] {
  return [...CATALOGUE.keys()]
}

/**
 * One function, one answer per entity - the form ENTITY_ART_MODE selected.
 *
 * `undefined` for an entity with no drawn art at all - a realm whose enemies
 * are not in the Mortal batch, or a test fixture. Callers that need "every
 * entity renders something" resolve `PLACEHOLDER_ENTITY_KEY` instead.
 */
export function presentationFor(entityKey: string): CombatEntityPresentation | undefined {
  return CATALOGUE.get(entityKey)
}

/**
 * The entity's ANIMATED form, whatever the mode emitted. Clip metadata exists
 * even while 'static' is active - the atlas/extent tests validate it against
 * the files on disk so the day the mode flips, the data is already honest.
 */
export function animatedArtFormFor(entityKey: string): CombatAnimationCatalogue | undefined {
  return ANIMATED_FORMS.get(entityKey)
}

/** The entity's STATIC form, whatever the mode emitted. See animatedArtFormFor. */
export function staticArtFormFor(
  entityKey: string,
): { texture: StaticEntityArt; idleMotion: IdleMotion } | undefined {
  return STATIC_FORMS.get(entityKey)
}

/**
 * Registered entity keys still pointing at placeholder art - derived, not
 * declared, so the answer cannot drift from the catalogue. In 'static' mode
 * the check is the silhouette texture key; in 'animated' mode the shared
 * sheet. This is the placeholder-art debt list; the ratchet guard is
 * tests/architecture/artPlaceholderDebt.test.ts (shrink freely, never grow).
 */
export function placeholderEntityKeys(): readonly string[] {
  const keys: string[] = []

  for (const [entityKey, presentation] of CATALOGUE) {
    if (entityKey === PLACEHOLDER_ENTITY_KEY) {
      continue
    }

    if (presentation.kind === 'animated') {
      const clips = Object.values(presentation.clips)

      if (clips.every((clip) => clip.sheetKey === PLACEHOLDER_SHEET_KEY)) {
        keys.push(entityKey)
      }
    } else if (presentation.texture.textureKey === PLACEHOLDER_STATIC_TEXTURE_KEY) {
      keys.push(entityKey)
    }
  }

  return keys
}

/** Every animated entity's clips, for preload and animation registration. */
export function animatedCombatEntities(): Array<{
  entityKey: string
  clips: CombatAnimationCatalogue
}> {
  const animated: Array<{ entityKey: string; clips: CombatAnimationCatalogue }> = []

  for (const [entityKey, presentation] of CATALOGUE) {
    if (presentation.kind === 'animated') {
      animated.push({ entityKey, clips: presentation.clips })
    }
  }

  return animated
}
