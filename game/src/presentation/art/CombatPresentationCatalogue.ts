/** Frame name for an index, matching what the generator wrote. */
export function placeholderFrameName(index: number): string {
  return `${PLACEHOLDER_FRAME_PREFIX}${String(index).padStart(PLACEHOLDER_ZERO_PAD, '0')}${PLACEHOLDER_FRAME_SUFFIX}`
}

/** Frame name for an index inside ANY atlas clip's naming scheme. */
export function atlasFrameName(clip: AtlasClip, index: number): string {
  return `${clip.framePrefix}${String(index).padStart(clip.zeroPad, '0')}${clip.frameSuffix}`
}

function playerMortalClip(
  entityKey: string,
  name: CombatAnimationName,
  firstFrame: number,
  lastFrame: number,
  frameRate: number,
  extent: AtlasClip['extent'],
  repeat: number,
): AtlasClip {
  return {
    key: combatAnimationKey(entityKey, name),
    sheetKey: PLAYER_MORTAL_ATLAS_SHEET_KEY,
    sheetUrl: PLAYER_MORTAL_ATLAS_SHEET_URL,
    atlasUrl: PLAYER_MORTAL_ATLAS_URL,
    framePrefix: PLAYER_MORTAL_FRAME_PREFIX,
    frameSuffix: PLAYER_MORTAL_FRAME_SUFFIX,
    zeroPad: PLAYER_MORTAL_ZERO_PAD,
    firstFrame,
    lastFrame,
    frameRate,
    sourceSize: {
      w: PLAYER_MORTAL_SOURCE_WIDTH,
      h: PLAYER_MORTAL_SOURCE_HEIGHT,
    },
    extent,
    repeat,
  }
}

/**
 * The mortal v2 atlas under the uniform contract (2026-09-19). Attack frames
 * (43-90: cast/sweep_hand/punch) and the old `ready` loop still exist in the
 * sheet but are dead art - the contract is idle/standby/death, and attacks
 * read through the shared lunge tween. No transition clips exist yet, so the
 * entity snaps between loops like every placeholder does.
 */
function playerMortalCatalogue(entityKey: string): CombatAnimationCatalogue {
  return {
    idle: playerMortalClip(entityKey, 'idle', 0, 31, 8, PLAYER_MORTAL_IDLE_EXTENT, -1),
    standby: playerMortalClip(entityKey, 'standby', 32, 42, 8, PLAYER_MORTAL_STANDBY_EXTENT, -1),
    death: playerMortalClip(entityKey, 'death', 91, 106, 10, PLAYER_MORTAL_DEATH_EXTENT, 0),
  }
}

/**
 * Which clip names MUST exist on every animated entity - the three combat
 * states. `COMBAT_ANIMATION_NAMES` additionally lists the optional ones
 * (transitions, cultivate) so tests can check "every declared key is a real
 * name" in both directions.
 */
export const REQUIRED_COMBAT_ANIMATION_NAMES = [
  'idle',
  'standby',
  'death',
] as const satisfies readonly CombatAnimationName[]

export const COMBAT_ANIMATION_NAMES: readonly CombatAnimationName[] = [
  ...REQUIRED_COMBAT_ANIMATION_NAMES,
  'idle_to_standby',
  'standby_to_idle',
  'cultivate',
]

/**
 * Shared-placeholder clips span the 32-frame sheet for every clip - the
 * placeholder has no authored states, so all three loops play the same
 * figure. No transition clips: an unauthored transition would freeze the
 * sprite for its full duration, which reads worse than the snap the
 * playback fallback produces.
 */
function placeholderClips(entityKey: string): CombatAnimationCatalogue {
  const clip = (name: CombatAnimationName): AtlasClip => ({
    key: combatAnimationKey(entityKey, name),
    sheetKey: PLACEHOLDER_SHEET_KEY,
    sheetUrl: PLACEHOLDER_SHEET_URL,
    atlasUrl: PLACEHOLDER_ATLAS_URL,
    framePrefix: PLACEHOLDER_FRAME_PREFIX,
    frameSuffix: PLACEHOLDER_FRAME_SUFFIX,
    zeroPad: PLACEHOLDER_ZERO_PAD,
    firstFrame: 0,
    lastFrame: PLACEHOLDER_FRAME_COUNT - 1,
    frameRate: PLACEHOLDER_FRAME_RATE,
    sourceSize: { w: PLACEHOLDER_FRAME_WIDTH, h: PLACEHOLDER_FRAME_HEIGHT },
    extent: {
      x: PLACEHOLDER_EXTENT_X,
      y: PLACEHOLDER_EXTENT_Y,
      w: PLACEHOLDER_EXTENT_W,
      h: PLACEHOLDER_EXTENT_H,
    },
    repeat: name === 'death' ? 0 : -1,
  })

  return {
    idle: clip('idle'),
    standby: clip('standby'),
    death: clip('death'),
  }
}

